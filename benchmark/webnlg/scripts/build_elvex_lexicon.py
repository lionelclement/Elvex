#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
from collections import Counter
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from lib.webnlg_utils import (
    read_jsonl,
    label_from_rdf,
    elvex_atom,
    elvex_lemma,
    find_determiners,
    predicate_guess,
    is_rdf_literal,
    is_raw_number,
    is_number_expression,
    parse_number_value,
)

FRAME_FOR_RE = __import__("re").compile(r"frame_for:([A-Za-z_][A-Za-z0-9_]*(?:\|[A-Za-z_][A-Za-z0-9_]*)*)")


def read_override_lines(path: Path) -> list[str]:
    if not path.exists():
        return []
    out: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        out.append(line)
    return out


def frame_heads_from_pattern_lines(lines: list[str]) -> set[str]:
    heads: set[str] = set()
    for line in lines:
        if line.lstrip().startswith("//"):
            continue
        m = FRAME_FOR_RE.search(line)
        if m:
            heads.update(x for x in m.group(1).split("|") if x)
    return heads


def read_overrides(path: Path) -> dict[str, dict[str, str]]:
    if not path.exists():
        return {}
    with path.open(encoding="utf-8", newline="") as f:
        return {r["predicate"]: r for r in csv.DictReader(f, delimiter="\t") if r.get("predicate") and not r["predicate"].lstrip().startswith("#")}


def fs_items(*items: str) -> str:
    cleaned = [x for x in items if x]
    return "[" + ", ".join(cleaned) + "]"


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Generate Elvex main.pattern, main.morpho and generated local lexicon files"
    )
    ap.add_argument("--triples", default=str(ROOT / "data/processed/triples.jsonl"))
    ap.add_argument("--user-dir", default=str(ROOT / "user"))
    ap.add_argument("--min-count", type=int, default=1)
    args = ap.parse_args()

    triples_path = Path(args.triples)
    if not triples_path.exists():
        raise SystemExit(f"Not found: {triples_path}. Run ./run extract first.")

    user_dir = Path(args.user_dir)
    lex_dir = user_dir / "lexicon"
    lex_dir.mkdir(parents=True, exist_ok=True)

    entities: Counter[str] = Counter()
    numeric_values: Counter[str] = Counter()
    predicates: Counter[str] = Counter()
    lex_texts: list[str] = []

    for row in read_jsonl(triples_path):
        lex_texts.extend(row.get("lexicalizations", []))
        for t in row["triples"]:
            subj_num = parse_number_value(t["subject"])
            obj_num = parse_number_value(t["object"])
            if subj_num:
                numeric_values[t["subject"]] += 1
            elif not is_rdf_literal(t["subject"]):
                entities[t["subject"]] += 1
            if obj_num:
                numeric_values[t["object"]] += 1
            elif not is_rdf_literal(t["object"]):
                entities[t["object"]] += 1
            predicates[t["predicate"]] += 1

    overrides = read_overrides(lex_dir / "predicate_overrides.tsv")
    user_override_pattern = read_override_lines(user_dir / "override.pattern")
    user_override_morpho = read_override_lines(user_dir / "override.morpho")
    frame_heads = frame_heads_from_pattern_lines(user_override_pattern)
    dets = sorted({"the", "a", "some", "this", "these"} | (find_determiners(lex_texts) - {"an"}))

    pattern_lines = [
        "// Auto-generated by scripts/build_elvex_lexicon.py.",
        "// Format: LEXEME<TAB>POS<TAB>LEMMA<TAB>features_1",
    ]
    morpho_lines = [
        "// Auto-generated by scripts/build_elvex_lexicon.py.",
        "// Format: FORM<TAB>POS<TAB>LEMMA<TAB>features_2",
    ]

    for ent, count in sorted(entities.items(), key=lambda kv: (-kv[1], kv[0].lower())):
        if count < args.min_count:
            continue
        lexeme = elvex_atom(ent, "E")
        lemma = elvex_lemma(ent)
        form = label_from_rdf(ent)
        pattern_lines.append(f"{lexeme}\tproper_noun\t{lemma}\t[HEAD:{lexeme}, source:webnlg_entity]")
        morpho_lines.append(f"{form}\tproper_noun\t{lemma}\t[@s]")

    suggestions_rows: list[tuple[str, str, str, str, str, str]] = []
    for pred, count in sorted(predicates.items(), key=lambda kv: (-kv[1], kv[0].lower())):
        guess = predicate_guess(pred)
        if pred in overrides:
            guess.update({k: v for k, v in overrides[pred].items() if v is not None and v != ""})
        pred_head = elvex_atom(pred, "P")
        if pred_head in frame_heads:
            suggestions_rows.append((pred, "frame", pred_head, "", "", str(count)))
            continue
        lexeme = elvex_atom(guess["lexeme"], "P")
        lemma = elvex_lemma(guess["lexeme"])
        form = guess["form"]
        pattern = guess["pattern"]
        if pattern == "cop_adj":
            pos = "adj"
            features = fs_items(f"HEAD:{pred_head}", "pattern:cop_adj")
        elif pattern == "cop_nom":
            pos = "nrel"
            features = fs_items(f"HEAD:{pred_head}", "pattern:cop_nom")
        elif pattern == "rel_nom":
            # Nominal relation, e.g. leaderName:
            #   The leader of X is Y. / Y is the leader of X.
            # The lexical entry is selected through HEAD:<predicate>, but the
            # produced form is a relational noun such as "leader".
            pos = "nrel"
            prep = guess.get("prep", "of") or "of"
            features = fs_items(f"HEAD:{pred_head}", "pattern:rel_nom", f"pcas:{prep}")
        else:
            pos = "vrel"
            features = fs_items(f"HEAD:{pred_head}", "pattern:svo")
        pattern_lines.append(f"{lexeme}\t{pos}\t{lemma}\t{features}")
        morpho_lines.append(f"{form}\t{pos}\t{lemma}\t[]")
        suggestions_rows.append((pred, pattern, lexeme, form, guess.get("prep", ""), str(count)))

    det_lines = [
        "/************************************************************",
        " * Auto-generated local determiners.",
        " * Closed-class entries only: no HEAD here.",
        " * Format: output-form<TAB>POS<TAB>features;",
        " ************************************************************/",
    ]
    for det in dets:
        # Generated determiners carry definiteness, and only true indefinite
        # articles carry indef:true. Possessives and quantifiers may be
        # def:false without being acceptable for a frame requesting @indef.
        if det in {"the"}:
            feats = "[def:true, poss:false, part:false, dem:false]"
        elif det in {"this", "that"}:
            feats = "[@s, def:true, poss:false, part:false, dem:true]"
        elif det in {"these", "those"}:
            feats = "[@p, def:true, poss:false, part:false, dem:true]"
        elif det == "a":
            feats = "[@s, @indef]"
        elif det == "":
            feats = "[@p, @indef]"
        elif det in {"each", "every"}:
            feats = f"[@s, indef:false, def:false, poss:false, part:false, dem:false, quant:{det}]"
        elif det in {"some", "all", "many", "few", "several", "any", "no"}:
            feats = f"[@p, indef:false, def:false, poss:false, part:false, dem:false, quant:{det}]"
        else:
            feats = "[indef:false, def:false, poss:false, part:false, dem:false]"
        escaped = det.replace('\\', '\\\\').replace(chr(34), '\\' + chr(34))
        det_lines.append(f'{chr(34)}{escaped}{chr(34)}\tdet\t{feats};')

    if user_override_pattern:
        pattern_lines.append("// User-maintained override.pattern is appended below.")
        pattern_lines.extend(user_override_pattern)
    if user_override_morpho:
        morpho_lines.append("// User-maintained override.morpho is appended below.")
        morpho_lines.extend(user_override_morpho)

    (user_dir / "main.pattern").write_text("\n".join(pattern_lines) + "\n", encoding="utf-8")
    (user_dir / "main.morpho").write_text("\n".join(morpho_lines) + "\n", encoding="utf-8")
    (lex_dir / "generated_determiners.lexicon").write_text("\n".join(det_lines) + "\n", encoding="utf-8")

    suggestions = lex_dir / "predicate_suggestions.tsv"
    with suggestions.open("w", encoding="utf-8", newline="") as f:
        wr = csv.writer(f, delimiter="\t")
        wr.writerow(["predicate", "pattern", "lexeme", "form", "prep", "count"])
        wr.writerows(suggestions_rows)

    print(f"Entities: {len(entities)}; numeric values excluded from compact lexicon: {len(numeric_values)}; predicates: {len(predicates)}; determiners: {len(dets)}")
    print(f"Pattern file written to {user_dir / 'main.pattern'}")
    print(f"Morphology file written to {user_dir / 'main.morpho'}")
    if frame_heads:
        print(f"Predicate frames declared by override.pattern: {len(frame_heads)}")
    print(f"Local determiner lexicon written to {lex_dir / 'generated_determiners.lexicon'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
